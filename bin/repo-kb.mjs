#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { repoRoot, getStagedFiles, getDiffNameOnly, getStagedAddedContent, getWorktreeChangedFiles } from "../lib/staged.mjs";
import { loadOntology, evaluateRules } from "../lib/rules.mjs";
import { buildIdIndex, scanForUnknownIds } from "../lib/ids.mjs";
import { runLlmPass } from "../lib/llm.mjs";

const SEVERITY_RANK = { warn: 1, error: 2 };

function parseArgs(argv) {
  const args = { _: [], flags: {} };
  for (const tok of argv) {
    if (tok.startsWith("--")) {
      const eq = tok.indexOf("=");
      if (eq >= 0) args.flags[tok.slice(2, eq)] = tok.slice(eq + 1);
      else args.flags[tok.slice(2)] = true;
    } else {
      args._.push(tok);
    }
  }
  return args;
}

function pickFiles(subcommand, args) {
  if (subcommand === "scan" && args.flags.staged) return getStagedFiles();
  if (subcommand === "check") {
    const ref = args.flags.ref || "HEAD~1";
    return getDiffNameOnly(ref);
  }
  return [];
}

function resolveOntologyPath(rootDir, args) {
  const raw = args.flags.ontology;
  if (!raw) return path.join(rootDir, "ontology.yml");
  return path.isAbsolute(raw) ? raw : path.join(rootDir, raw);
}

function summariseFinding(f) {
  const head = `[${f.severity.toUpperCase()}] ${f.rule}: ${f.message}`;
  const lines = [head];
  if (f.triggered_by?.length) {
    lines.push(`  triggered by: ${f.triggered_by.slice(0, 5).join(", ")}` +
      (f.triggered_by.length > 5 ? ` (+${f.triggered_by.length - 5} more)` : ""));
  }
  if (f.expected_any_of?.length) {
    lines.push(`  expected any of: ${f.expected_any_of.slice(0, 5).join(", ")}` +
      (f.expected_any_of.length > 5 ? ` (+${f.expected_any_of.length - 5} more)` : ""));
  }
  return lines.join("\n");
}

function reportPath(rootDir) {
  return path.join(rootDir, ".repo-kb", "last-report.json");
}

function statusPath(rootDir) {
  return path.join(rootDir, ".repo-kb", "STATUS.md");
}

function writeReport(rootDir, payload) {
  const dir = path.dirname(reportPath(rootDir));
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(reportPath(rootDir), JSON.stringify(payload, null, 2) + "\n");
}

function listRunSnapshots(rootDir) {
  const base = path.join(rootDir, ".repo-kb", "runs");
  if (!fs.existsSync(base)) return [];
  const entries = fs.readdirSync(base, { withFileTypes: true });
  const snapshots = [];
  for (const e of entries) {
    if (!e.isDirectory()) continue;
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e.name)) continue;
    const indexPath = path.join(base, e.name, "index.md");
    if (!fs.existsSync(indexPath)) continue;
    let verdict = "unknown";
    let scenarioCount = 0;
    try {
      const text = fs.readFileSync(indexPath, "utf8");
      const v = text.match(/^- \*\*Suite verdict:\*\*\s*`?([a-z]+)`?/im);
      if (v) verdict = v[1].toLowerCase();
      const tableLines = text.split(/\r?\n/).filter((l) => /^\|\s*\d/.test(l));
      scenarioCount = tableLines.length;
    } catch {
      // ignore
    }
    snapshots.push({ date: e.name, verdict, scenarioCount });
  }
  snapshots.sort((a, b) => b.date.localeCompare(a.date));
  return snapshots;
}

function summarizeFindings(findings) {
  let err = 0;
  let warn = 0;
  for (const f of findings) {
    if (f.severity === "error") err++;
    else if (f.severity === "warn") warn++;
  }
  return { err, warn, total: findings.length };
}

function renderFindingsTable(findings) {
  if (findings.length === 0) return ["_No findings._"];
  const out = [];
  out.push("| Severity | Rule | Triggered by |");
  out.push("| --- | --- | --- |");
  for (const f of findings) {
    const trig = (f.triggered_by || []).slice(0, 3).map((p) => "`" + p + "`").join(", ") || "—";
    out.push(`| ${f.severity} | \`${f.rule}\` | ${trig} |`);
  }
  return out;
}

function renderStatus(ontology, lastReport, snapshots, live) {
  const lines = [];
  lines.push("# Repo Coherence - Current State");
  lines.push("");
  lines.push("_Generated by `repo-kb status`. Overwritten on each refresh. The rules engine is **diff-based**: it flags transitions (file A changed without file B), not steady-state coherence._");
  lines.push("");
  lines.push("## Repo Coherence — Right Now");
  lines.push("");
  lines.push("_Computed live from the current git state. Rules-only, no LLM pass. Pair this with any project-specific docs or link checks you maintain._");
  lines.push("");
  lines.push(`### Last commit (\`${live.last.range}\`)`);
  lines.push("");
  if (live.last.files.length === 0) {
    lines.push("_No files changed in this range._");
  } else {
    const s = summarizeFindings(live.last.findings);
    lines.push(`- Files changed: ${live.last.files.length}`);
    lines.push(`- Findings: **${s.err} error**, **${s.warn} warn**, ${s.total} total`);
    lines.push("");
    for (const ln of renderFindingsTable(live.last.findings)) lines.push(ln);
  }
  lines.push("");
  lines.push("### Working tree (uncommitted vs `HEAD`)");
  lines.push("");
  if (live.worktree.files.length === 0) {
    lines.push("_Working tree clean._");
  } else {
    const s = summarizeFindings(live.worktree.findings);
    lines.push(`- Files changed: ${live.worktree.files.length}`);
    lines.push(`- Findings: **${s.err} error**, **${s.warn} warn**, ${s.total} total`);
    lines.push("");
    for (const ln of renderFindingsTable(live.worktree.findings)) lines.push(ln);
  }
  lines.push("");
  lines.push("## Scenario Run History");
  lines.push("");
  lines.push("_Optional scenario snapshots under `.repo-kb/runs/`. They are separate from the live repository state above._");
  lines.push("");
  if (snapshots.length === 0) {
    lines.push("_No self-test runs recorded yet._");
  } else {
    const latest = snapshots[0];
    lines.push(`- Latest run: **${latest.date}**, scenarios: ${latest.scenarioCount}, self-test verdict: **${latest.verdict}**`);
      lines.push(`- Index: [\`.repo-kb/runs/${latest.date}/index.md\`](./runs/${latest.date}/index.md)`);
    if (snapshots.length > 1) {
      lines.push("");
      lines.push("| Date | Self-test verdict | Scenarios | Index |");
      lines.push("| --- | --- | --- | --- |");
      for (const s of snapshots.slice(0, 10)) {
        lines.push(`| ${s.date} | ${s.verdict} | ${s.scenarioCount} | [open](./${s.date}/index.md) |`);
      }
    }
  }
  lines.push("");
  lines.push("## Active Rules");
  lines.push("");
  lines.push("| Rule | Severity | When | Expect Any Of |");
  lines.push("| --- | --- | --- | --- |");
  for (const r of ontology.rules) {
    const when = r.when.map((g) => "`" + g + "`").join(", ");
    const expect = r.expect_any.map((g) => "`" + g + "`").join(", ");
    lines.push(`| \`${r.id}\` | ${r.severity} | ${when} | ${expect} |`);
  }
  lines.push("");
  lines.push("## LLM Pass Configuration");
  lines.push("");
  lines.push("- Provider: Groq (OpenAI-compatible Chat Completions endpoint).");
  lines.push("- Default model: `llama-3.3-70b-versatile`; override via `ZEN_REPO_KB_GROQ_MODEL`.");
  lines.push("- Enable per-run with `ZEN_REPO_KB_LLM=1` (or `--llm`); requires `GROQ_API_KEY`.");
  lines.push("- Hard cap: 3 calls per commit; findings are always `warn`.");
  lines.push("");
  lines.push("## Last Ephemeral Scan");
  lines.push("");
  lines.push("_This block reflects the most recent `repo-kb` invocation on this machine (from `.repo-kb/last-report.json`, gitignored). For substantive run history, see the committed snapshots above._");
  lines.push("");
  if (!lastReport) {
    lines.push("_No `.repo-kb/last-report.json` on disk yet. Run `npm run check:staged` or `npm run check` to generate one._");
  } else {
    lines.push(`- Subcommand: \`${lastReport.subcommand}\``);
    lines.push(`- Generated: ${lastReport.generated_at}`);
    lines.push(`- Files inspected: ${lastReport.files?.length ?? 0}`);
    lines.push(`- Rules loaded: ${lastReport.ruleCount}`);
    const llm = lastReport.llm || {};
    lines.push(`- LLM: ${llm.skipped ? `skipped (${llm.skipped})` : `${llm.model}, ${llm.calls} call(s)`}`);
    lines.push(`- Findings: ${lastReport.findings?.length ?? 0}`);
    if (lastReport.findings?.length) {
      lines.push("");
      lines.push("| Severity | Rule | Message |");
      lines.push("| --- | --- | --- |");
      for (const f of lastReport.findings) {
        const msg = (f.message || "").replace(/\|/g, "\\|");
        lines.push(`| ${f.severity} | \`${f.rule}\` | ${msg} |`);
      }
    }
  }
  lines.push("");
  lines.push("## How to refresh this page");
  lines.push("");
  lines.push("```bash");
  lines.push("npm run status                         # rewrite .repo-kb/STATUS.md");
  lines.push("npm run check                          # dry-run against HEAD~1");
  lines.push("ZEN_REPO_KB_LLM=1 npm run check:staged # staged set, with Groq pass");
  lines.push("```");
  lines.push("");
  return lines.join("\n");
}

function computeLive(ontology, rootDir) {
  const lastRange = "HEAD~1..HEAD";
  let lastFiles = [];
  try {
    lastFiles = getDiffNameOnly(lastRange, rootDir);
  } catch {
    lastFiles = [];
  }
  const lastFindings = evaluateRules(ontology, lastFiles);

  const worktreeFiles = getWorktreeChangedFiles(rootDir);
  const worktreeFindings = evaluateRules(ontology, worktreeFiles);

  return {
    last: { range: lastRange, files: lastFiles, findings: lastFindings },
    worktree: { files: worktreeFiles, findings: worktreeFindings }
  };
}

function writeStatus(rootDir, ontology) {
  let lastReport = null;
  const rp = reportPath(rootDir);
  if (fs.existsSync(rp)) {
    try {
      lastReport = JSON.parse(fs.readFileSync(rp, "utf8"));
    } catch {
      lastReport = null;
    }
  }
  const snapshots = listRunSnapshots(rootDir);
  const live = computeLive(ontology, rootDir);
  const out = statusPath(rootDir);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, renderStatus(ontology, lastReport, snapshots, live));
  return out;
}

async function runScan({ files, useLlm, rootDir, ontologyPath }) {
  const ontology = loadOntology(ontologyPath);
  const ruleFindings = evaluateRules(ontology, files);

  const idIndex = buildIdIndex(rootDir);
  const addedByNonMd = {};
  for (const rel of files) {
    if (rel.endsWith(".md")) continue;
    addedByNonMd[rel] = getStagedAddedContent(rel, rootDir);
  }
  const idFindings = scanForUnknownIds(addedByNonMd, idIndex);

  const llmResult = await runLlmPass({ stagedFiles: files, enabled: useLlm, rootDir });

  return {
    ruleCount: ontology.rules.length,
    findings: [...ruleFindings, ...idFindings, ...llmResult.findings],
    llm: { skipped: llmResult.skipped, calls: llmResult.calls ?? 0, model: llmResult.model ?? null }
  };
}

function printReport({ files, ruleCount, findings, llm }) {
  console.log(`repo-kb: ${files.length} file(s), ${ruleCount} rules loaded`);
  if (llm.skipped) {
    console.log(`repo-kb: llm pass skipped (${llm.skipped})`);
  } else {
    console.log(`repo-kb: llm pass via ${llm.model}, ${llm.calls} call(s)`);
  }
  if (findings.length === 0) {
    console.log("repo-kb: no findings.");
    return;
  }
  console.log(`repo-kb: ${findings.length} finding(s):`);
  for (const f of findings) console.log(summariseFinding(f));
}

function maxSeverity(findings) {
  let rank = 0;
  for (const f of findings) rank = Math.max(rank, SEVERITY_RANK[f.severity] || 0);
  return rank;
}

async function main() {
  const [, , subRaw, ...rest] = process.argv;
  const sub = subRaw || "scan";
  const args = parseArgs(rest);

  if (sub === "help" || args.flags.help) {
    console.log(
      "repo-kb <subcommand> [flags]\n" +
        "  scan --staged [--llm] [--ontology=path]  evaluate staged files\n" +
        "  check [--ref=HEAD~1] [--ontology=path]   evaluate a diff range\n" +
        "  report                   print the last report stored at .repo-kb/last-report.json\n" +
        "  status [--ontology=path] rewrite .repo-kb/STATUS.md (current state)\n" +
        "env:\n" +
        "  ZEN_REPO_KB_OFF=1        skip all checks, exit 0\n" +
        "  ZEN_REPO_KB_LLM=1        enable LLM semantic pass (requires GROQ_API_KEY)\n" +
        "  ZEN_REPO_KB_GROQ_MODEL   override Groq model id (default: llama-3.3-70b-versatile)\n"
    );
    return 0;
  }

  if (process.env.ZEN_REPO_KB_OFF === "1") {
    console.error("repo-kb: ZEN_REPO_KB_OFF=1 set; skipping coherence checks");
    return 0;
  }

  const rootDir = repoRoot();
  const ontologyPath = resolveOntologyPath(rootDir, args);

  if (sub === "report") {
    const p = reportPath(rootDir);
    if (!fs.existsSync(p)) {
      console.error("repo-kb: no report on disk yet");
      return 0;
    }
    process.stdout.write(fs.readFileSync(p, "utf8"));
    return 0;
  }

  if (sub === "status") {
    const ontology = loadOntology(ontologyPath);
    const out = writeStatus(rootDir, ontology);
    console.log(`repo-kb: wrote ${path.relative(rootDir, out)}`);
    return 0;
  }

  if (sub !== "scan" && sub !== "check") {
    console.error(`repo-kb: unknown subcommand '${sub}'. Try 'help'.`);
    return 2;
  }

  const files = pickFiles(sub, args);
  const useLlm = Boolean(args.flags.llm);
  const { ruleCount, findings, llm } = await runScan({ files, useLlm, rootDir, ontologyPath });

  writeReport(rootDir, {
    subcommand: sub,
    flags: args.flags,
    files,
    ruleCount,
    llm,
    findings,
    generated_at: new Date().toISOString()
  });

  printReport({ files, ruleCount, findings, llm });

  return maxSeverity(findings) >= SEVERITY_RANK.error ? 1 : 0;
}

main().then(
  (code) => process.exit(code),
  (err) => {
    console.error("repo-kb: fatal:", err.stack || err.message);
    process.exit(2);
  }
);
